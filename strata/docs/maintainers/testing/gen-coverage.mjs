#!/usr/bin/env node
/**
 * Coverage-matrix generator.
 *
 *   node strata/docs/maintainers/testing/gen-coverage.mjs          # regenerate .md + .html
 *   node strata/docs/maintainers/testing/gen-coverage.mjs --check  # validate only, exit 1 on drift
 *
 * Reads coverage.data.mjs (the source of truth) and the real test files, then:
 *   1. Validates the matrix against the tests — INVARIANT: for every component with a dedicated
 *      `<Name>.test.tsx`, its number of "ok" behavior rows must equal the file's `it()` count.
 *      Also flags test files missing from the matrix, and matrix "ok" rows with no test file.
 *   2. Emits `component-coverage.md` and `coverage-matrix.html` (the published artifact source).
 *
 * Zero dependencies — plain Node ESM.
 */
import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, resolve, join } from "node:path";
import data from "./coverage.data.mjs";

const HERE = dirname(fileURLToPath(import.meta.url));
const STRATA_ROOT = resolve(HERE, "../../.."); // testing → maintainers → docs → strata
const TEST_DIR = resolve(STRATA_ROOT, data.meta.testDir);
const CHECK = process.argv.includes("--check");

const SYM = { ok: "✅", partial: "🟡", gap: "⬜", browser: "🌐" };

/** Components that actually have a `<Name>.test.tsx` file — populated in the run section below. */
let FILE_SET = new Set();

// ---- 1. Read the real tests: it()-count per component (file basename) ----
// Match `it(` / `test(` (with optional .only/.skip/.todo), NOT when part of a larger identifier
// like `emit(` — a negative lookbehind for word chars guards that.
const IT_RE = /(?<![\w$])(?:it|test)(?:\.(?:only|skip|todo|concurrent|each))?\s*\(\s*(['"`])((?:\\.|(?!\1).)*)\1/g;

function readTests() {
  const files = readdirSync(TEST_DIR).filter((f) => f.endsWith(".test.tsx"));
  const byComponent = new Map(); // name -> { count, titles[] }
  for (const f of files) {
    const name = f.replace(/\.test\.tsx$/, "");
    const src = readFileSync(join(TEST_DIR, f), "utf8");
    const titles = [...src.matchAll(IT_RE)].map((m) => m[2]);
    byComponent.set(name, { count: titles.length, titles });
  }
  return byComponent;
}

// ---- 2. Validate the matrix against the tests ----
function validate(tests) {
  const problems = [];
  const dataNames = new Set();

  for (const tier of data.tiers) {
    for (const c of tier.components) {
      dataNames.add(c.name);
      const okRows = c.behaviors.filter((b) => b[0] === "ok").length;
      const t = tests.get(c.name);
      if (t) {
        if (okRows !== t.count) {
          problems.push(
            `DRIFT  ${c.name}: ${t.count} it() in the test file but ${okRows} "ok" behavior row(s) in the matrix. ` +
              `Add/remove an "ok" row in coverage.data.mjs.`,
          );
        }
      } else if (okRows > 0) {
        problems.push(
          `DRIFT  ${c.name}: matrix lists ${okRows} "ok" behavior(s) but there is no ${c.name}.test.tsx.`,
        );
      }
    }
  }
  for (const name of tests.keys()) {
    if (!dataNames.has(name)) {
      problems.push(`ORPHAN ${name}.test.tsx exists but ${name} is not in the matrix (coverage.data.mjs).`);
    }
  }
  return problems;
}

// ---- Totals (shared by both renderers) ----
function totals() {
  let comp = 0, tested = 0, beh = 0, ok = 0, part = 0, brow = 0, gap = 0;
  for (const t of data.tiers) {
    for (const c of t.components) {
      comp++;
      if (FILE_SET.has(c.name)) tested++;
      for (const b of c.behaviors) {
        beh++;
        if (b[0] === "ok") ok++;
        else if (b[0] === "partial") part++;
        else if (b[0] === "browser") brow++;
        else gap++;
      }
    }
  }
  return { comp, tested, beh, ok, part, brow, gap, pct: Math.round((ok / beh) * 100) };
}

// ---- 3a. Render Markdown ----
function renderMarkdown(T, stamp, testTotal) {
  const L = [];
  L.push(`# Component test coverage — \`@strata/core-map\` React layer`, "");
  L.push(`<!-- GENERATED by gen-coverage.mjs from coverage.data.mjs — do not edit by hand. -->`, "");
  L.push(
    `The living definition of "feature complete" for the core-map React layer: every component, the`,
    `behaviors that matter, and whether a test exercises them. Regenerate with`,
    `\`node ${data.meta.mdPath.replace(/component-coverage\.md$/, "gen-coverage.mjs")}\`.`,
    "",
  );
  L.push(`**Status:** ${SYM.ok} covered · ${SYM.partial} partial · ${SYM.browser} browser-only · ${SYM.gap} no test yet`, "");
  L.push(
    `**Totals:** ${testTotal} tests green. Components with a dedicated test file: **${T.tested} / ${T.comp}**. ` +
      `Behaviors covered: **${T.ok} / ${T.beh}** (${T.pct}%). Open items: **${T.gap + T.part}**.`,
    "",
  );

  for (const tier of data.tiers) {
    const tested = tier.components.filter((c) => FILE_SET.has(c.name)).length;
    L.push(`## ${tier.name} (${tested} / ${tier.components.length}) — ${tier.tag}`, "");
    L.push(`| Component | Cov. | Behaviors |`, `|---|---|---|`);
    for (const c of tier.components) {
      const cov = c.behaviors.filter((b) => b[0] === "ok" || b[0] === "partial").length;
      const cell = c.behaviors.map((b) => `${SYM[b[0]]} ${b[1]}`).join("<br>");
      const noteLine = c.note ? `<br>_${c.note}_` : "";
      L.push(`| \`${c.name}\` | ${cov}/${c.behaviors.length} | ${cell}${noteLine} |`);
    }
    L.push("");
  }

  // Open items, grouped.
  L.push(`## Open items`, "");
  for (const tier of data.tiers) {
    const rows = [];
    for (const c of tier.components) {
      for (const b of c.behaviors) {
        if (b[0] === "gap" || b[0] === "partial") rows.push(`- ${SYM[b[0]]} \`${c.name}\` — ${b[1]}`);
      }
    }
    if (rows.length) {
      L.push(`**${tier.name}**`, "", ...rows, "");
    }
  }
  L.push(`_Generated ${stamp}._`, "");
  return L.join("\n");
}

// ---- 3b. Render HTML (fill the template) ----
function renderHtml(stamp, testTotal, T) {
  const tpl = readFileSync(join(HERE, "coverage-template.html"), "utf8");
  const footer = [
    `<span>Generated by <code>gen-coverage.mjs</code> from <code>coverage.data.mjs</code></span>`,
    `<span>Behaviors validated against <code>${data.meta.testDir}/*.test.tsx</code></span>`,
    `<span>${testTotal} tests green · ${T.ok}/${T.beh} behaviors · ${stamp}</span>`,
  ].join("\n    ");
  return tpl
    .replaceAll("/*__TIERS__*/[]", JSON.stringify(data.tiers))
    .replaceAll("/*__HASFILE__*/[]", JSON.stringify([...FILE_SET]))
    .replaceAll("__FOOTER__", footer);
}

// ---- run ----
const tests = readTests();
FILE_SET = new Set(tests.keys()); // components that actually have a test file
const problems = validate(tests);

if (problems.length) {
  console.error(`\n✗ Coverage matrix is out of sync with the tests:\n`);
  for (const p of problems) console.error("  " + p);
  console.error("");
  if (CHECK) process.exit(1);
  console.error("  (regenerating anyway; fix coverage.data.mjs to clear these)\n");
} else {
  console.log("✓ Matrix matches the tests (ok-row count == it() count for every tested component).");
}

const T = totals();
const testTotal = [...tests.values()].reduce((n, t) => n + t.count, 0);
const stamp = new Date().toISOString().slice(0, 10);

if (CHECK) {
  console.log(`  ${T.tested}/${T.comp} components tested · ${T.ok}/${T.beh} behaviors (${T.pct}%) · ${testTotal} component tests`);
  process.exit(problems.length ? 1 : 0);
}

writeFileSync(join(HERE, "component-coverage.md"), renderMarkdown(T, stamp, testTotal));
writeFileSync(join(HERE, "coverage-matrix.html"), renderHtml(stamp, testTotal, T));
console.log(`  Wrote component-coverage.md and coverage-matrix.html`);
console.log(`  ${T.tested}/${T.comp} components tested · ${T.ok}/${T.beh} behaviors (${T.pct}%) · ${testTotal} component tests`);
